#!/usr/bin/env node

/**
 * 🚀 AETH-1 GitHub Preview Connector
 * 
 * Automates GitHub Pages deployment for instant previews
 * This is the "bridge" solution until IDE has built-in preview
 * 
 * Usage:
 *   node github-preview-connector.js --token <GITHUB_TOKEN> --repo <REPO_NAME>
 *   
 * Features:
 *   ✅ Creates public preview repo automatically
 *   ✅ Deploys HTML to GitHub Pages
 *   ✅ Returns permanent preview URL
 *   ✅ Updates existing previews on re-run
 *   ✅ Zero manual intervention needed
 */

const https = require('https');
const { execSync } = require('child_process');
const fs = require('fs');
const path = require('path');

// Colors for terminal output
const colors = {
  reset: '\x1b[0m',
  green: '\x1b[32m',
  yellow: '\x1b[33m',
  blue: '\x1b[34m',
  red: '\x1b[31m',
  cyan: '\x1b[36m'
};

function log(message, color = 'reset') {
  console.log(`${colors[color]}${message}${colors.reset}`);
}

/**
 * Make authenticated GitHub API request
 */
async function githubRequest(token, endpoint, method = 'GET', data = null) {
  return new Promise((resolve, reject) => {
    const url = new URL(`https://api.github.com${endpoint}`);
    const options = {
      hostname: url.hostname,
      path: url.pathname + url.search,
      method,
      headers: {
        'Authorization': `token ${token}`,
        'Accept': 'application/vnd.github+json',
        'User-Agent': 'AETH-1-Preview-Connector',
        'Content-Type': 'application/json'
      }
    };

    const req = https.request(options, (res) => {
      let body = '';
      res.on('data', chunk => body += chunk);
      res.on('end', () => {
        try {
          resolve({ status: res.statusCode, data: JSON.parse(body) });
        } catch (e) {
          resolve({ status: res.statusCode, data: body });
        }
      });
    });

    req.on('error', reject);
    
    if (data) {
      req.write(JSON.stringify(data));
    }
    
    req.end();
  });
}

/**
 * Main GitHub Preview Connector Class
 */
class GitHubPreviewConnector {
  constructor(token, username) {
    this.token = token;
    this.username = username;
    this.apiBase = '/user';
  }

  /**
   * Create or get public preview repository
   */
  async ensurePreviewRepo(repoName) {
    log(`\n📁 Ensuring preview repo: ${repoName}`, 'cyan');
    
    // Check if repo exists
    const checkResult = await githubRequest(
      this.token, 
      `/repos/${this.username}/${repoName}`
    );

    if (checkResult.status === 200) {
      log(`✅ Preview repo already exists`, 'green');
      return checkResult.data.html_url;
    }

    // Create new public repo
    log(`📦 Creating new public preview repo...`, 'yellow');
    
    const createResult = await githubRequest(this.token, '/user/repos', 'POST', {
      name: repoName,
      description: '🚀 AETH-1 Platform Live Preview (Auto-generated)',
      public: true,
      has_issues: false,
      has_projects: false,
      has_wiki: false,
      auto_init: false
    });

    if (createResult.status === 201) {
      log(`✅ Created public repo: ${createResult.data.html_url}`, 'green');
      return createResult.data.html_url;
    }

    throw new Error(`Failed to create repo: ${createResult.data.message}`);
  }

  /**
   * Deploy HTML file to preview repo
   */
  async deployPreview(sourceHtmlPath, previewRepoName) {
    log(`\n🚀 Deploying preview to GitHub Pages...`, 'cyan');
    
    const tempDir = `/tmp/aeth-preview-${Date.now()}`;
    
    try {
      // Create temp directory
      fs.mkdirSync(tempDir, { recursive: true });
      
      // Initialize git repo
      execSync(`cd "${tempDir}" && git init`, { stdio: 'pipe' });
      execSync(`cd "${tempDir}" && git config user.email "aeth-1@preview.connector"`, { stdio: 'pipe' });
      execSync(`cd "${tempDir}" && git config user.name "AETH-1 Preview Bot"`, { stdio: 'pipe' });
      
      // Copy HTML file as index.html
      const htmlContent = fs.readFileSync(sourceHtmlPath, 'utf8');
      fs.writeFileSync(path.join(tempDir, 'index.html'), htmlContent);
      
      // Add README for context
      const readme = `# AETH-1 Platform Preview

🚀 **Live Preview of AETH-1 Advanced Enterprise Technology Hub**

## What This Is
This is an auto-generated preview of the AETH-1 platform.
Deployed via [GitHub Preview Connector](https://github.com/aeth-1/future-insights-platform).

## Main Repository
🔒 Private source code: https://github.com/${this.username}/future-insights-platform

---
*Generated by AETH-1 AI Assistant • Last updated: ${new Date().toISOString()}*
`;
      fs.writeFileSync(path.join(tempDir, 'README.md'), readme);

      // Commit and push
      execSync(`cd "${tempDir}" && git add .`, { stdio: 'pipe' });
      execSync(`cd "${tempDir}" && git commit -m "🌐 Update preview - ${new Date().toISOString()}"`, { stdio: 'pipe' });
      
      // Set remote and push
      const remoteUrl = `https://${this.token}@github.com/${this.username}/${previewRepoName}.git`;
      execSync(`cd "${tempDir}" && git remote add origin "${remoteUrl}"`, { stdio: 'pipe' });
      execSync(`cd "${tempDir}" && git push -u origin main --force`, { stdio: 'pipe', timeout: 60000 });

      log(`✅ Code pushed successfully!`, 'green');

      return true;

    } finally {
      // Cleanup temp directory
      if (fs.existsSync(tempDir)) {
        fs.rmSync(tempDir, { recursive: true, force: true });
      }
    }
  }

  /**
   * Enable GitHub Pages for the preview repo
   */
  async enableGitHubPages(previewRepoName) {
    log(`\n⚙️  Enabling GitHub Pages...`, 'cyan');
    
    const result = await githubRequest(
      this.token,
      `/repos/${this.username}/${previewRepoName}/pages`,
      'POST',
      {
        source: {
          branch: 'main',
          path: '/'
        },
        build_type: 'legacy'
      }
    );

    if (result.status === 201 || result.status === 200) {
      const pagesUrl = result.data.html_url;
      log(`✅ GitHub Pages enabled!`, 'green');
      return pagesUrl;
    }

    // If already enabled or any error, get current status
    if (result.status >= 400) {
      log(`   GitHub Pages may be configured, checking...`, 'yellow');
      try {
        const existing = await githubRequest(
          this.token,
          `/repos/${this.username}/${previewRepoName}/pages`
        );
        if (existing.data?.html_url) {
          log(`✅ Using existing GitHub Pages URL`, 'green');
          return existing.data.html_url;
        }
      } catch (e) {
        // Continue to throw
      }
    }

    throw new Error(`Failed to enable GitHub Pages: ${result.data?.message || result.status}`);
  }

  /**
   * Wait for GitHub Pages to be ready
   */
  async waitForDeployment(previewRepoName, maxWaitMs = 120000) {
    log(`\n⏳ Waiting for GitHub Pages deployment...`, 'yellow');
    log(`(This usually takes 30-60 seconds)`, 'cyan');
    
    const startTime = Date.now();
    const interval = 10000; // Check every 10 seconds
    
    while (Date.now() - startTime < maxWaitMs) {
      const result = await githubRequest(
        this.token,
        `/repos/${this.username}/${previewRepoName}/pages`
      );
      
      const status = result.data?.status;
      const elapsed = Math.round((Date.now() - startTime) / 1000);
      
      if (status === 'built' || status === 'served') {
        log(`\n✅ GitHub Pages is LIVE! (${elapsed}s)`, 'green');
        return result.data.html_url;
      }
      
      if (status === 'building' || status === 'build_queued') {
        log(`   [${elapsed}s] Status: ${status}...`, 'yellow');
      } else {
        log(`   [${elapsed}s] Status: ${status}`, 'cyan');
      }
      
      // Wait before next check
      await new Promise(resolve => setTimeout(resolve, interval));
    }
    
    throw new Error('Timeout waiting for GitHub Pages deployment');
  }

  /**
   * Full deployment pipeline
   */
  async deploy(sourceHtmlPath, options = {}) {
    const {
      previewRepoName = 'aeth-1-preview',
      mainRepoName = 'future-insights-platform'
    } = options;

    console.log('\n' + '='.repeat(60));
    console.log('🚀 AETH-1 GitHub Preview Connector');
    console.log('='.repeat(60));
    console.log(`\n📍 Source: ${sourceHtmlPath}`);
    console.log(`🔑 User: ${this.username}`);
    console.log(`📦 Preview Repo: ${previewRepoName}`);

    try {
      // Step 1: Ensure preview repo exists
      await this.ensurePreviewRepo(previewRepoName);
      
      // Step 2: Deploy HTML to repo
      await this.deployPreview(sourceHtmlPath, previewRepoName);
      
      // Step 3: Enable GitHub Pages
      const pagesUrl = await this.enableGitHubPages(previewRepoName);
      
      // Step 4: Wait for deployment
      const liveUrl = await this.waitForDeployment(previewRepoName);
      
      // Success!
      console.log('\n' + '='.repeat(60));
      console.log('🎉 DEPLOYMENT SUCCESSFUL!');
      console.log('='.repeat(60));
      console.log(`\n🌐 Your LIVE Preview URL:`);
      console.log(`   ${colors.cyan}${liveUrl}${colors.reset}\n`);
      
      console.log('📋 Summary:');
      console.log(`   • Private Code: https://github.com/${this.username}/${mainRepoName}`);
      console.log(`   • Public Preview: ${liveUrl}`);
      console.log(`   • Status: ✅ LIVE & ACCESSIBLE\n`);
      
      return {
        success: true,
        previewUrl: liveUrl,
        privateRepoUrl: `https://github.com/${this.username}/${mainRepoName}`,
        publicRepoUrl: `https://github.com/${this.username}/${previewRepoName}`
      };

    } catch (error) {
      console.error(`\n❌ Deployment failed: ${error.message}`, 'red');
      throw error;
    }
  }
}

// CLI Interface
async function main() {
  const args = process.argv.slice(2);
  
  // Parse arguments
  const tokenIdx = args.indexOf('--token');
  const repoIdx = args.indexOf('--repo');
  const sourceIdx = args.indexOf('--source');
  const helpIdx = args.indexOf('--help') || args.indexOf('-h');
  
  if (helpIdx !== -1 || !args.length) {
    console.log(`
🚀 AETH-1 GitHub Preview Connector
====================================

Usage:
  node github-preview-connector.js --token <TOKEN> [--options]

Required:
  --token <TOKEN>     GitHub Personal Access Token

Options:
  --source <PATH>     Path to HTML file (default: ./download/AETH-1-FULL-APPLICATION.html)
  --repo <NAME>       Preview repo name (default: aeth-1-preview)
  --help, -h          Show this help

Examples:
  # Quick deploy with defaults
  node github-preview-connector.js --token ghp_xxxx

  # Custom source file
  node github-preview-connector.js --token ghp_xxxx --source ./dist/index.html

  # Custom preview repo name
  node github-preview-connector.js --token ghp_xxxx --repo my-app-preview
`);
    process.exit(0);
  }

  if (tokenIdx === -1) {
    console.error('❌ --token is required');
    process.exit(1);
  }

  const token = args[tokenIdx + 1];
  const sourceFile = sourceIdx !== -1 ? args[sourceIdx + 1] : './download/AETH-1-FULL-APPLICATION.html';
  const previewRepo = repoIdx !== -1 ? args[repoIdx + 1] : 'aeth-1-preview';

  // Get username from API
  const userResult = await githubRequest(token, '/user');
  const username = userResult.data.login;

  // Run deployment
  const connector = new GitHubPreviewConnector(token, username);
  
  // Resolve source path
  const sourcePath = path.resolve(sourceFile);
  
  if (!fs.existsSync(sourcePath)) {
    console.error(`❌ Source file not found: ${sourcePath}`);
    process.exit(1);
  }

  await connector.deploy(sourcePath, {
    previewRepoName: previewRepo
  });
}

// Export for programmatic use
module.exports = { GitHubPreviewConnector };

// Run if called directly
if (require.main === module) {
  main().catch(err => {
    console.error('Fatal error:', err);
    process.exit(1);
  });
}
